"""File classification + language detection (Phase 0/1).

Categories: production | test | generated | vendor | config | unknown.
"""

from __future__ import annotations

import os
import re

_TEST_PATTERNS = (
    re.compile(r"(^|/)(test_|_test\.|tests?/|testing/|spec\.|__tests__/)", re.I),
    re.compile(r"\.(test|spec)\.[a-z]+$", re.I),
    re.compile(r"conftest\.py$", re.I),
    re.compile(r"fixtures?/", re.I),
)

_GENERATED_PATTERNS = (
    re.compile(r"(^|/)(generated/|gen/|\.generated\.)", re.I),
    re.compile(r"_pb2\.py$", re.I),
    re.compile(r"\.g\.dart$", re.I),
    re.compile(r"package-lock\.json$|yarn\.lock$|pnpm-lock\.yaml$", re.I),
)

_VENDOR_PATTERNS = (
    re.compile(r"(^|/)(vendor/|third_party/|node_modules/|\.venv/|venv/)", re.I),
)

_CONFIG_EXTS = {".toml", ".yaml", ".yml", ".json", ".ini", ".cfg", ".env"}

_EXT_LANG = {
    ".py": "python", ".js": "javascript", ".ts": "typescript", ".tsx": "typescript",
    ".jsx": "javascript", ".java": "java", ".go": "go", ".c": "c", ".h": "c",
    ".cpp": "cpp", ".cc": "cpp", ".cs": "csharp", ".rb": "ruby", ".rs": "rust",
    ".php": "php", ".swift": "swift", ".kt": "kotlin", ".scala": "scala",
    ".sh": "shell", ".sql": "sql",
}

_GENERATED_MARKERS = ("@generated", "auto-generated", "do not edit", "generated by")


def classify(path: str) -> str:
    p = path.replace(os.sep, "/")
    if any(rx.search(p) for rx in _VENDOR_PATTERNS):
        return "vendor"
    if any(rx.search(p) for rx in _GENERATED_PATTERNS):
        return "generated"
    if any(rx.search(p) for rx in _TEST_PATTERNS):
        return "test"
    _, ext = os.path.splitext(p)
    if ext.lower() in _CONFIG_EXTS:
        return "config"
    return "production"


def detect_language(path: str) -> str:
    _, ext = os.path.splitext(path)
    return _EXT_LANG.get(ext.lower(), "unknown")


def looks_generated_content(head: str) -> bool:
    low = head[:2000].lower()
    return any(m in low for m in _GENERATED_MARKERS)
